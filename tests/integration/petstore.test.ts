import { execSync } from 'child_process';
import { readFileSync, writeFileSync, mkdirSync, rmSync } from 'fs';
import { mkdtemp } from 'fs/promises';
import { tmpdir } from 'os';
import { join, dirname } from 'path';
import { fileURLToPath } from 'url';

import { describe, it, expect, beforeAll, afterAll } from 'vitest';

import { generateClient, generateFullOutput } from '../../src/generator/client-generator.js';
import { generateContracts } from '../../src/generator/contracts-generator.js';
import { RefResolver } from '../../src/parser/ref-resolver.js';
import { loadFromFile } from '../../src/parser/spec-reader.js';
import type { GeneratorConfig } from '../../src/types/client.js';
import type { OpenAPIDocument } from '../../src/types/openapi.js';

const __dirname = dirname(fileURLToPath(import.meta.url));
const FIXTURE_PATH = join(__dirname, '../fixtures/petstore.yaml');

const TSC_FLAGS = [
  '--strict',
  '--noEmit',
  '--esModuleInterop',
  '--module',
  'NodeNext',
  '--moduleResolution',
  'NodeNext',
  '--target',
  'ES2022',
  '--skipLibCheck',
].join(' ');

describe('Petstore integration', () => {
  let doc: OpenAPIDocument;
  let contracts: string;
  let client: string;
  let tmpDir: string;

  beforeAll(async () => {
    doc = await loadFromFile(FIXTURE_PATH);
    const config: GeneratorConfig = {
      input: FIXTURE_PATH,
      outputDir: '/tmp/petstore-test',
    };
    const result = generateClient(doc, config);
    contracts = result.contracts;
    client = result.client;
  });

  // 1. Load and generate
  it('loads petstore.yaml and produces contracts and client strings', async () => {
    expect(doc).toBeDefined();
    expect(doc.openapi).toBe('3.1.0');
    expect(doc.info.title).toBe('Pet Store');

    expect(typeof contracts).toBe('string');
    expect(typeof client).toBe('string');
    expect(contracts.length).toBeGreaterThan(0);
    expect(client.length).toBeGreaterThan(0);

    expect(contracts).toContain('// Auto-generated by genoc from OpenAPI 3.1.0 spec. DO NOT EDIT.');
    expect(client).toContain('// Auto-generated by genoc from OpenAPI 3.1.0 spec. DO NOT EDIT.');
  });

  // 2. Contracts compile with tsc
  it('generated contracts compile with tsc --strict --noEmit', async () => {
    tmpDir = await mkdtemp(join(tmpdir(), 'petstore-contracts-'));
    const contractsFile = join(tmpDir, 'contracts.ts');
    writeFileSync(contractsFile, contracts, 'utf-8');

    const result = execSync(`npx tsc ${TSC_FLAGS} ${contractsFile}`, {
      cwd: tmpDir,
      encoding: 'utf-8',
      timeout: 30000,
    }).trim();

    // tsc --noEmit produces no output on success
    expect(result).toBe('');
  });

  // 3. Client compiles with tsc (needs contracts file alongside)
  it('generated client compiles with tsc --strict --noEmit', async () => {
    const dir = await mkdtemp(join(tmpdir(), 'petstore-client-'));
    writeFileSync(join(dir, 'contracts.ts'), contracts, 'utf-8');
    writeFileSync(join(dir, 'client.ts'), client, 'utf-8');

    const result = execSync(`npx tsc ${TSC_FLAGS} client.ts`, {
      cwd: dir,
      encoding: 'utf-8',
      timeout: 30000,
    }).trim();

    expect(result).toBe('');
  });

  // 4. Method names correct
  it('generates correct method names using path-based strategy', () => {
    expect(client).toContain('getPets: decorateWithErrors<');
    expect(client).toContain('getPetsByPetId: decorateWithErrors<');
    expect(client).toContain('postPets: decorateWithErrors<');
    expect(client).toContain('putPetsByPetId: decorateWithErrors<');
    expect(client).toContain('deletePetsByPetId: decorateWithErrors<');
  });

  // 5. Method signatures correct
  it('generates correct method signatures — path params flat, query grouped, body last', () => {
    expect(client).toMatch(/\(query\?: GetPetsQuery\) => Promise<GetPetsResponse>/);

    expect(client).toMatch(/\(petId: string\) => Promise<GetPetsPetIdResponse>/);

    expect(client).toMatch(/\(body: PostPetsBody\) => Promise<PostPetsResponse>/);

    expect(client).toMatch(
      /\(petId: string, body: PutPetsPetIdBody\) => Promise<PutPetsPetIdResponse>/
    );

    expect(client).toMatch(/\(petId: string\) => Promise<void>/);
  });

  // 6. Error types generated
  it('generates error types for non-2xx responses', () => {
    // Per-operation error types
    expect(contracts).toContain('GetPetsError400');
    expect(contracts).toContain('GetPetsError500');
    expect(contracts).toContain('GetPetsErrors');

    expect(contracts).toContain('PostPetsError400');
    expect(contracts).toContain('PostPetsError500');
    expect(contracts).toContain('PostPetsErrors');

    expect(contracts).toContain('GetPetsPetIdError404');
    expect(contracts).toContain('GetPetsPetIdError500');
    expect(contracts).toContain('GetPetsPetIdErrors');

    expect(contracts).toContain('PutPetsPetIdError400');
    expect(contracts).toContain('PutPetsPetIdError404');
    expect(contracts).toContain('PutPetsPetIdError500');
    expect(contracts).toContain('PutPetsPetIdErrors');

    expect(contracts).toContain('DeletePetsPetIdError400');
    expect(contracts).toContain('DeletePetsPetIdError404');
    expect(contracts).toContain('DeletePetsPetIdError500');
    expect(contracts).toContain('DeletePetsPetIdErrors');

    // Error union uses ApiError wrapper
    expect(contracts).toContain('ApiError<');

    // ApiError class present
    expect(contracts).toContain(
      'export class ApiError<TStatus extends number, TData> extends Error'
    );
  });

  // 7. Schema types correct
  it('generates correct schema types from components/schemas', () => {
    expect(contracts).toContain('export type Pet = {');
    expect(contracts).toContain('export type NewPet = {');
    expect(contracts).toContain('export type Error = {');

    // Pet fields
    expect(contracts).toMatch(/id: string/);
    expect(contracts).toMatch(/name: string/);
    expect(contracts).toMatch(/tag\?: string/);

    // Error fields
    expect(contracts).toMatch(/code: number/);
    expect(contracts).toMatch(/message: string/);
  });

  // 8. Snapshot tests
  it('matches contracts snapshot', () => {
    expect(contracts).toMatchSnapshot('petstore-contracts');
  });

  it('matches client snapshot', () => {
    expect(client).toMatchSnapshot('petstore-client');
  });
});

describe('Petstore full output pipeline', () => {
  let tmpDir: string;

  beforeAll(async () => {
    tmpDir = await mkdtemp(join(tmpdir(), 'petstore-full-'));
    const doc = await loadFromFile(FIXTURE_PATH);
    const config: GeneratorConfig = {
      input: FIXTURE_PATH,
      outputDir: tmpDir,
    };
    await generateFullOutput(doc, config);
  });

  afterAll(() => {
    rmSync(tmpDir, { recursive: true, force: true });
  });

  it('writes contracts.ts and client.ts to disk', () => {
    const contractsFile = join(tmpDir, 'contracts.ts');
    const clientFile = join(tmpDir, 'client.ts');

    const contractsContent = readFileSync(contractsFile, 'utf-8');
    const clientContent = readFileSync(clientFile, 'utf-8');

    expect(contractsContent).toContain('export type Pet = {');
    expect(contractsContent).toContain('export type NewPet = {');
    expect(contractsContent).toContain('export type Error = {');
    expect(contractsContent).toContain('export class ApiError');

    expect(clientContent).toContain('export function createClient');
    expect(clientContent).toContain("from './contracts.js'");
    expect(clientContent).toContain('getPets: decorateWithErrors<');
    expect(clientContent).toContain('postPets: decorateWithErrors<');
    expect(clientContent).toContain('getPetsByPetId: decorateWithErrors<');
    expect(clientContent).toContain('putPetsByPetId: decorateWithErrors<');
    expect(clientContent).toContain('deletePetsByPetId: decorateWithErrors<');
  });

  it('generated files on disk compile together with tsc', () => {
    const result = execSync(`npx tsc ${TSC_FLAGS} client.ts contracts.ts`, {
      cwd: tmpDir,
      encoding: 'utf-8',
      timeout: 30000,
    }).trim();

    expect(result).toBe('');
  });
});
